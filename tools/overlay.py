"""Put a post's cover (kicker, title, lead, logo, footer) over a Higgsfield clip.

    python3 overlay.py <slug> <clip.mp4> [--out DIR]

Produces in DIR (default out/<slug>/):
  cover-4x5.mp4   1080x1350 — replaces slide 01 of the carousel
  reel-9x16.mp4   1080x1920 — the same cover as a Reel
  cover-4x5.jpg   a still frame for the Reel cover / preview

The clip is scaled to cover the frame and center-cropped. The text sits in the
upper part over a dark scrim, so prompts ask Higgsfield to keep the subject in
the lower half and leave the top dark and empty. No text is generated by the
video model: Cyrillic from video models comes out garbled.
"""
import argparse
import pathlib
import subprocess
import sys

from playwright.sync_api import sync_playwright

HERE = pathlib.Path(__file__).resolve().parent
sys.path.insert(0, str(HERE))
import build_posts as bp  # noqa: E402

OVERLAY_CSS = """
<style>
body { background: transparent !important; }
.slide { background: transparent !important; margin: 0 !important; }
.grid { display: none; }
.scrim { position: absolute; inset: 0; pointer-events: none;
  background: linear-gradient(180deg, rgba(11,10,8,.92) 0%, rgba(11,10,8,.80) 38%, rgba(11,10,8,.18) 62%, rgba(11,10,8,0) 74%, rgba(11,10,8,.55) 100%); }
.slide > *:not(.scrim) { position: relative; }
.tall .idx { visibility: hidden; }
.tall { height: 1920px !important; padding-top: 150px !important; padding-bottom: 150px !important; }
</style>
"""


def overlay_pngs(slug, out):
    slides = bp.POSTS[slug]
    kind, inner, right = slides[0]
    total = len(slides)
    sec = bp.slide("ov", 1, total, inner, right or "Далі →")
    sec = sec.replace('<div class="grid"></div>', '<div class="scrim"></div>', 1)
    tall = sec.replace('id="ov"', 'id="ovt"').replace('class="slide"', 'class="slide tall"', 1)
    # The reel has no "swipe" — point to the carousel instead.
    tall = tall.replace(bp.SWIPE, "Карусель у профілі")
    head = bp.head.replace("</head>", OVERLAY_CSS + "</head>")
    html = head + "<body>" + bp.defs + sec + tall + "</body></html>"
    page_path = out / "_overlay.html"
    page_path.write_text(html)
    with sync_playwright() as p:
        b = p.chromium.launch()
        pg = b.new_page(viewport={"width": 1080, "height": 1920})
        pg.goto(page_path.resolve().as_uri())
        pg.evaluate("document.fonts.ready")
        pg.wait_for_timeout(500)
        pg.locator("#ov").screenshot(path=str(out / "_ov-4x5.png"), omit_background=True)
        pg.locator("#ovt").screenshot(path=str(out / "_ov-9x16.png"), omit_background=True)
        b.close()
    page_path.unlink()
    return out / "_ov-4x5.png", out / "_ov-9x16.png"


def composite(clip, png, w, h, dst):
    vf = (f"[0:v]scale={w}:{h}:force_original_aspect_ratio=increase,crop={w}:{h},"
          f"fps=30,format=yuv420p[bg];[bg][1:v]overlay=0:0:format=auto,format=yuv420p")
    cmd = ["ffmpeg", "-y", "-loglevel", "error", "-i", str(clip), "-i", str(png),
           "-filter_complex", vf, "-an", "-c:v", "libx264", "-profile:v", "high",
           "-pix_fmt", "yuv420p", "-crf", "18", "-movflags", "+faststart", str(dst)]
    subprocess.run(cmd, check=True)


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("slug")
    ap.add_argument("clip")
    ap.add_argument("--out")
    a = ap.parse_args()
    if a.slug not in bp.POSTS:
        sys.exit(f"unknown slug: {a.slug}")
    out = pathlib.Path(a.out) if a.out else HERE / "out" / a.slug
    out.mkdir(parents=True, exist_ok=True)
    o45, o916 = overlay_pngs(a.slug, out)
    composite(a.clip, o45, 1080, 1350, out / "cover-4x5.mp4")
    composite(a.clip, o916, 1080, 1920, out / "reel-9x16.mp4")
    subprocess.run(["ffmpeg", "-y", "-loglevel", "error", "-ss", "1.5", "-i", str(out / "cover-4x5.mp4"),
                    "-frames:v", "1", "-q:v", "2", str(out / "cover-4x5.jpg")], check=True)
    o45.unlink(); o916.unlink()
    print("\n".join(str(out / f) for f in ("cover-4x5.mp4", "reel-9x16.mp4", "cover-4x5.jpg")))


if __name__ == "__main__":
    main()
